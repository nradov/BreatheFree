DRAWABLES_XML = """<drawables>
    <bitmap id="LauncherIcon" filename="launcher_icon.png" />
</drawables>
"""

BEGIN = "# BEGIN launcher icons (generated by tools/make_launcher_icons.py)"
END = "# END launcher icons"


def render(master, size, folder):
    os.makedirs(folder, exist_ok=True)
    master.resize((size, size), Image.LANCZOS).save(os.path.join(folder, "launcher_icon.png"))
    with open(os.path.join(folder, "drawables.xml"), "w") as f:
        f.write(DRAWABLES_XML)


def main():
    master = Image.open(os.path.join(ROOT, "art", "launcher_icon.png")).convert("RGBA")
    manifest = open(os.path.join(ROOT, "manifest.xml")).read()
    products = re.findall(r'product id="([^"]+)"', manifest)
    unknown = [p for p in products if p not in SIZES]
    if unknown:
        sys.exit("No launcher icon size for: " + ", ".join(unknown))

    render(master, DEFAULT, os.path.join(ROOT, "resources", "drawables"))
    lines = [BEGIN,
             "# Devices not listed use resources/drawables ({0}x{0}).".format(DEFAULT)]
    for size in sorted({SIZES[p] for p in products} - {DEFAULT}):
        render(master, size, os.path.join(ROOT, "resources-launcher-%dx%d" % (size, size), "drawables"))
    for p in products:
        if SIZES[p] != DEFAULT:
            lines.append("%s.resourcePath = $(%s.resourcePath);resources-launcher-%dx%d" % (p, p, SIZES[p], SIZES[p]))
    lines.append(END)

    jungle_path = os.path.join(ROOT, "monkey.jungle")
    jungle = open(jungle_path).read()
    block = "\n".join(lines) + "\n"
    if BEGIN in jungle:
        jungle = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", lambda m: block, jungle, flags=re.S)
    else:
        jungle = jungle.rstrip("\n") + "\n\n" + block
    open(jungle_path, "w").write(jungle)
    print("Icons written for %d devices" % len(products))


if __name__ == "__main__":
    main()
